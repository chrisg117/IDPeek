#!/usr/bin/env python3
# Builds the IDPeek_Data addon (spell -> visuals -> kits, WorldEffect -> model file) from 7.3.5 .db2 files.
# usage: build_data.py <dbc dir> <out dir>
#
# Fields, pinned from the 26972 files with rel.py:
#   SpellXSpellVisual  field 0 = SpellVisualID, parent = spell
#   SpellVisualEvent   field 7 = SpellVisualKitID, parent = SpellVisual
#   WorldEffect        field 4 = QuestFeedbackEffectID
#   QuestFeedbackEffect field 0 = FileDataID, field 2 = attach point
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import wdc1, rel

ROWS_PER_BLOCK = 2000   # keeps each Lua function under 5.1's constant limit


def _table(dbc, name):
    path = os.path.join(dbc, name)
    return wdc1.read(path)["records"], rel.parents(path)


def load_spells(dbc):
    xsv, xsv_par = _table(dbc, "SpellXSpellVisual.db2")
    ev, ev_par = _table(dbc, "SpellVisualEvent.db2")
    kits = {}
    for i, (rid, vals) in enumerate(ev):
        kit = vals[7][0]
        if kit:
            kits.setdefault(ev_par.get(i), set()).add(kit)
    spells = {}
    for i, (rid, vals) in enumerate(xsv):
        visual = vals[0][0]
        if visual not in kits:
            continue
        rows = spells.setdefault(xsv_par.get(i), [])
        if not any(r[0] == visual for r in rows):
            rows.append([visual] + sorted(kits[visual]))
    return spells


def load_worldeffects(dbc):
    we, _ = _table(dbc, "WorldEffect.db2")
    qfe, _ = _table(dbc, "QuestFeedbackEffect.db2")
    models = {rid: (vals[0][0], vals[2][0]) for rid, vals in qfe if vals[0][0]}
    return {rid: models[vals[4][0]] for rid, vals in we if vals[4][0] in models}


def write_lua(spells, worldeffects, out):
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "IDPeek_Data.toc"), "w", newline="\n") as f:
        f.write("## Interface: 70300\n## Title: IDPeek Data\n## LoadOnDemand: 1\n## Dependencies: IDPeek\nData.lua\n")
    lines = ["-- Generated by IDPeek/tools/build_data.py; do not edit.", "IDPeek_Data={spell={},worldeffect={}}"]

    def blocks(name, items, row):
        items = sorted(items)
        for start in range(0, len(items), ROWS_PER_BLOCK):
            lines.append("(function() local s=IDPeek_Data.%s" % name)
            lines.extend(row(k, v) for k, v in items[start:start + ROWS_PER_BLOCK])
            lines.append("end)()")

    blocks("spell", spells.items(),
           lambda k, v: "s[%d]={%s}" % (k, ",".join("{%s}" % ",".join(map(str, r)) for r in v)))
    blocks("worldeffect", worldeffects.items(), lambda k, v: "s[%d]={%d,%d}" % (k, v[0], v[1]))
    with open(os.path.join(out, "Data.lua"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    dbc, out = sys.argv[1], sys.argv[2]
    spells, worldeffects = load_spells(dbc), load_worldeffects(dbc)
    write_lua(spells, worldeffects, out)
    print("spells", len(spells), "worldeffects", len(worldeffects),
          "Data.lua bytes", os.path.getsize(os.path.join(out, "Data.lua")))
